const { Pool } = require('pg');

function replacePlaceholders(sql) {
    let index = 0;
    let output = '';
    let quote = null;
    for (let cursor = 0; cursor < sql.length; cursor += 1) {
        const character = sql[cursor];
        if (quote) {
            output += character;
            if (character === quote && sql[cursor - 1] !== '\\') quote = null;
            continue;
        }
        if (character === "'" || character === '"') {
            quote = character;
            output += character;
        } else if (character === '?') {
            index += 1;
            output += `$${index}`;
        } else {
            output += character;
        }
    }
    return output;
}

function convertSql(sql) {
    return replacePlaceholders(String(sql))
        .replace(/`/g, '"')
        .replace(/\bAS\s+([a-z][A-Za-z0-9]*[A-Z][A-Za-z0-9]*)\b/g, 'AS "$1"')
        .replace(/\bPRIMARY KEY\s+AUTO_INCREMENT\b/gi, 'GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
        .replace(/\bUNSIGNED\b/gi, '')
        .replace(/\bMEDIUMTEXT\b/gi, 'TEXT')
        .replace(/\bDATETIME\b/gi, 'TIMESTAMP')
        .replace(/\bTINYINT\b/gi, 'SMALLINT')
        .replace(/\bAUTO_INCREMENT\b/gi, 'GENERATED BY DEFAULT AS IDENTITY')
        .replace(/\s+ON UPDATE CURRENT_TIMESTAMP/gi, '')
        .replace(/\s+AFTER\s+[a-zA-Z0-9_]+/gi, '')
        .replace(/DATE_SUB\(NOW\(\),\s*INTERVAL\s+(\d+)\s+HOUR\)/gi, "NOW() - INTERVAL '$1 hours'")
        .replace(/\bUUID\(\)/gi, 'gen_random_uuid()')
        .replace(/DATE_FORMAT\(CURRENT_DATE,\s*'%Y-%m-01'\)/gi, "(date_trunc('month', CURRENT_DATE))::date")
        .replace(/DATE_FORMAT\(([^,]+),\s*'%Y-%m'\)/gi, "to_char($1, 'YYYY-MM')")
        .replace(/UPDATE\s+(\w+)\s+(\w+)\s+JOIN\s+(\w+)\s+(\w+)\s+ON\s+(.+?)\s+SET\s+(.+)$/i, (_match, table, alias, joinTable, joinAlias, condition, assignments) => `UPDATE ${table} AS ${alias} SET ${assignments.replace(new RegExp(`\\b${alias}\\.`, 'g'), '')} FROM ${joinTable} AS ${joinAlias} WHERE ${condition}`)
        .replace(/CURDATE\(\)/gi, 'CURRENT_DATE')
        .replace(/IFNULL\(/gi, 'COALESCE(')
        .replace(/SUM\((?:(\w+)\.)?(\w+)\s*=\s*'([^']+)'\)/gi, (_match, table, column, value) => `SUM(CASE WHEN ${table ? `${table}.` : ''}${column} = '${value}' THEN 1 ELSE 0 END)`)
        .replace(/INSERT\s+IGNORE\s+INTO/gi, 'INSERT INTO')
        .replace(/ON\s+DUPLICATE\s+KEY\s+UPDATE/gi, 'ON CONFLICT DO UPDATE SET')
        .replace(/\bVALUES\s*\(\s*([a-zA-Z0-9_]+)\s*\)/gi, 'EXCLUDED.$1')
        .replace(/\s+ENGINE\s*=\s*[^\s;]+/gi, '')
        .replace(/\s+DEFAULT\s+CHARSET\s*=\s*[^\s;]+/gi, '')
        .replace(/\s+COLLATE\s*=\s*[^\s;]+/gi, '')
        .replace(/\bENUM\s*\([^)]*\)/gi, 'VARCHAR(40)')
        .replace(/ALTER\s+TABLE\s+(\w+)\s+MODIFY\s+(?:COLUMN\s+)?(\w+)\s+([A-Z]+(?:\(\d+\))?)\s+NOT\s+NULL\s*,\s*MODIFY\s+(?:COLUMN\s+)?(\w+)\s+([A-Z]+(?:\(\d+\))?)\s+NULL/gi, 'ALTER TABLE $1 ALTER COLUMN $2 TYPE $3, ALTER COLUMN $5 TYPE $6')
        .replace(/ALTER\s+TABLE\s+(\w+)\s+MODIFY\s+(?:COLUMN\s+)?(\w+)\s+([A-Z]+(?:\(\d+\))?)\s+NOT\s+NULL\s+DEFAULT\s+'[^']*'/gi, 'ALTER TABLE $1 ALTER COLUMN $2 TYPE $3')
        .replace(/ALTER\s+TABLE\s+(\w+)\s+MODIFY\s+(?:COLUMN\s+)?(\w+)\s+([A-Z]+(?:\(\d+\))?)\s+NOT\s+NULL(?:\s+UNIQUE)?/gi, 'ALTER TABLE $1 ALTER COLUMN $2 TYPE $3')
        .replace(/\bUNIQUE\s+KEY\s+[a-zA-Z0-9_]+\s*\(([^)]*)\)/gi, 'UNIQUE ($1)')
        .replace(/\bINDEX\s+[a-zA-Z0-9_]+\s*\([^)]*\),?/gi, '')
        .replace(/\bKEY\s+[a-zA-Z0-9_]+\s*\([^)]*\),?/gi, '')
        .replace(/\bMODIFY\s+COLUMN\b/gi, 'ALTER COLUMN')
        .replace(/SUBSTRING_INDEX\(([^,]+),\s*' ',\s*1\)/gi, "split_part($1, ' ', 1)")
        .replace(/SUBSTRING_INDEX\(([^,]+),\s*' ',\s*-1\)/gi, "split_part($1, ' ', array_length(string_to_array($1, ' '), 1))")
        .replace(/CREATE\s+DATABASE[^;]+;?/gi, '')
        .replace(/^\s*USE\s+[^;]+;?/gim, '');
}

function normalizeArrayParameters(sql, values) {
    return sql.replace(/\bIN\s*\(\$(\d+)\)/gi, (match, position) => {
        const index = Number(position) - 1;
        return Array.isArray(values[index]) ? `= ANY($${position})` : match;
    });
}

function normalizeSql(sql) {
    const converted = convertSql(sql);
    return /^\s*CREATE\s+TABLE\b/i.test(converted) ? converted.replace(/,\s*\)\s*$/, '\n)') : converted;
}

function isInsert(sql) {
    return /^\s*INSERT\s+INTO\s/i.test(sql);
}

function withReturningId(sql) {
    if (!isInsert(sql) || /\bRETURNING\b/i.test(sql)) return sql;
    return `${sql.replace(/;\s*$/, '')} RETURNING id`;
}

function createResult(result) {
    return [result.rows, { affectedRows: result.rowCount || 0, insertId: result.rows[0]?.id }];
}

function explainConnectionError(error) {
    if (error?.code === 'ENOTFOUND') {
        error.message = `Cannot resolve database host "${process.env.DB_HOST || 'from DATABASE_URL'}". Copy the exact Supabase Direct connection or Session pooler host into backend/.env.`;
    }
    return error;
}

function wrapClient(client) {
    return {
        async query(sql, values = []) {
            const converted = normalizeArrayParameters(normalizeSql(sql), values);
            try {
                return createResult(await client.query(withReturningId(converted), values));
            } catch (error) {
                if (isInsert(converted) && /column [\"']?id[\"']? does not exist/i.test(error.message)) {
                    return createResult(await client.query(converted, values));
                }
                throw explainConnectionError(error);
            }
        },
        execute(sql, values = []) { return this.query(sql, values); },
        async beginTransaction() { await client.query('BEGIN'); },
        async commit() { await client.query('COMMIT'); },
        async rollback() { await client.query('ROLLBACK'); },
        release() { client.release?.(); },
    };
}

function createPool() {
    const connectionString = process.env.DATABASE_URL;
    const host = process.env.DB_HOST;
    if (!connectionString && !host) {
        throw new Error('Database configuration is missing. Set DATABASE_URL or DB_HOST in backend/.env.');
    }
    const pool = new Pool(connectionString ? { connectionString, ssl: { rejectUnauthorized: false } } : {
        host,
        port: Number(process.env.DB_PORT || 5432),
        user: process.env.DB_USER,
        password: process.env.DB_PASSWORD,
        database: process.env.DB_NAME || 'postgres',
        ssl: String(process.env.DB_SSL || 'true').toLowerCase() === 'true' ? { rejectUnauthorized: false } : false,
        max: Number(process.env.DB_POOL_SIZE || 10),
        keepAlive: true,
    });
    return {
        query(sql, values = []) { return wrapClient(pool).query(sql, values); },
        async getConnection() {
            try { return wrapClient(await pool.connect()); } catch (error) { throw explainConnectionError(error); }
        },
        end() { return pool.end(); },
        async ping() { const client = await pool.connect(); try { await client.query('SELECT 1'); } finally { client.release(); } },
    };
}

module.exports = { createPool, convertSql, normalizeSql };
